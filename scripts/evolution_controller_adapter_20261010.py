#!/usr/bin/env python3
"""Fail-closed controller adapter; next-generation runner calls after each generation.

This adapter does NOT infer statistical confidence from raw candidate EV.
The review must be generated by a separately certified archive auditor.
"""
import json,pathlib
from scripts.evolution_review_policy_20261010 import POLICY
from scripts.evolution_safety_20261010 import atomic_json
def review_gate(out,generation,last_credible_generation):
    out=pathlib.Path(out)
    reviews_file=out/"economic_reviews.jsonl"
    reviews=[json.loads(s) for s in reviews_file.read_text().splitlines() if s.strip()] if reviews_file.exists() else []
    decision=POLICY.decide(generation,last_credible_generation,reviews)
    if generation%25==0:
        atomic_json(out/"economic_controller_state.json",{
            "generation":generation,"last_credible_generation":last_credible_generation,
            "stagnant_generations":generation-last_credible_generation,
            "decision":decision,"review_required":decision=="REVIEW_REQUIRED"})
    return decision
def require_launch_clearance(out):
    """Never auto-start a second experiment on an unverified predecessor."""
    p=pathlib.Path(out)/"scientific_completion.json"
    if not p.exists():return False
    d=json.loads(p.read_text())
    return all(d.get(k) is True for k in
        ("finished_cleanly","lineage_verified","archive_verified",
         "risk_audited","confidence_audited","next_study_preflight_passed"))
